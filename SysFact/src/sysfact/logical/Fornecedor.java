package sysfact.logical;

/**
 *
 * @author JM-Tecnologias
 */
public class Fornecedor {
    private int id;
    private String nome;
    private int nuit;
    private boolean estadoActive;
    
    public Fornecedor(){}

    public Fornecedor(int id, String nome, int nuit, boolean estadoActive) {
        this.id = id;
        this.nome = nome;
        this.nuit = nuit;
        this.estadoActive = estadoActive;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getNuit() {
        return nuit;
    }

    public void setNuit(int nuit) {
        this.nuit = nuit;
    }

    public boolean isEstadoActive() {
        return estadoActive;
    }

    public void setEstadoActive(boolean estadoActive) {
        this.estadoActive = estadoActive;
    }
    
    
}
